//
//  输出接口与 full_top.sample_l 完全一致：
//      每个 sample_stb 送一个 16 位有符号采样（48 kHz）
//  所以可以无差别地接到 vis_top.sample_l。
//
//  循环节奏（48 kHz 下）：
//      音色  每 32768 采样 ≈ 0.68 s 换一个（8 个循环）
//      音高  每 131072 采样 ≈ 2.73 s 换一个（C3/E3/G3/C4）
//      响度  每 524288 采样 ≈ 10.9 s 换一档（响/中/轻/很响）
//
//  用 sample_stb 当节拍（而不是自己分频）：与真实音频同一时刻更新，
//  这样 vis_audio 里那套握手/锁相能按真实条件被验证到。
//============================================================================
